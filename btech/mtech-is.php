                        <h2 class="text-primary">M.Tech - IS</h2>
                        
                        <h3 class="text-primary">About the Programme:</h3>
                        <p class="text-justify">Information security protects information systems from unauthorized access, use, disclosure, disruption, modification, or destruction. The goals include protecting the confidentiality, integrity, and availability of information. Information security is one of the cornerstones for the continued expansion and acceptance of the information society. It is also a fundamental research discipline within computer science, with many open theoretical and applied problems.</p>
                        <p class="text-justify">One of the main paradigm shifts in the emerging information society is that information is stored and exchanged electronically. This electronic representation differs radically from traditional representations; for instance, electronic data can be copied without cost, erased without leaving traces, and communicated without effort over large distances. The downside of these features is that protecting information, crucial for the information society, has become fundamentally more difficult.</p>
                        
                    </div>
