                       <p>This is the problem that research in information security addresses, both in terms of finding solutions to pressing security problems and laying the foundations for developing a secure information infrastructure for the future. </p>
                        
                        <p class="text-justify">All organizations, including governments, military, financial institutions, hospitals, and private businesses, assimilate and store a huge amount of confidential information about their employees, customers, products, and research and financial operations. Most information is collected, processed, and stored electronically and transmitted across networks to other computers. In many cases, protecting confidential information is a business requirement and an ethical and legal requirement. Information security has a significant effect on maintaining the privacy and preventing identity theft of any individual. Our IS M.Tech Programme is the need of the hour as information security plays a fundamental role in several areas of computer science today and is imperative to address such serious problems as information identity threats.</p>

                        <h3 class="text-primary">Scope:</h3>
                        <p class="text-justify">The course is designed to provide a balanced mixture of theoretical and professional training in Cryptology and Information Security. Upon successful completion of the course, students have the choice to take up either: <br>(a)&nbsp;a professional career in information security or specialized application areas <br>Or (b) an academic career for further study and research in the theoretical and applied aspects of Cryptology, Information Security, and related disciplines.</p>

                        <h3 class="text-primary">Career Opportunities:</h3>
                        <p class="text-justify">Security is a major concern in all organizations. In particular, governments and industries worldwide have forecast a shortage of and high demand for information security professionals. One can expect good employment prospects with local and multinational businesses, governments, financial and banking institutions, and consulting firms such as I.T. security specialists, I.T. security auditors, network and systems specialists, and I.T. security product developers and solution providers.</p>
                        <h3 class="text-primary">Objectives:</h3>
                        <p class="text-justify">A 2-year full-time M.Tech Programme in Information Security is being planned to develop and enhance the skills of professionals in the following areas:</p>
                        <ol>
                            <li>Analyzing the network security threats</li>
                            <li>Analyzing the network traffic</li>
                            <li>Knowledge gained on various attack methods</li>
                            <li>In-depth understanding of core system technologies from a security point of view</li>
                            <li>In-depth understanding of cryptography</li>
                            <li>In-depth understanding of security tools implementation and internals</li>
                            <li>Usage of security tools and technologies</li>
                            <li>Analyzing new security requirements and developing new tools</li>
                        </ol>
